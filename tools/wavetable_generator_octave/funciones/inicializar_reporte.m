function fileID = inicializar_reporte(ruta)
    fileID = fopen(ruta, 'w');
    fprintf(fileID, '===========================================================================================================================================\n');
    fprintf(fileID, '                 REPORTE ESTADÍSTICO DE SÍNTESIS WAVETABLE (V4.1.0-alpha)                     \n');
    fprintf(fileID, '===========================================================================================================================================\n');
    fprintf(fileID, '%-12s %-11s %-11s %-9s %-8s %-9s %-9s %-11s %-9s %-11s %-9s %-8s\n', ...
        'Nota', 'F.Teorica', 'F.Real', 'Dif(Hz)', 'Dif(%)', 'MSE.G', 'SC.G', 'LSD.G(dB)', 'SC.B', 'LSD.B(dB)', 'Dif CFR', 'Dur(s)');
    fprintf(fileID, '--------------------------------------------------------------------------------------------------------------------------------------------\n');
end

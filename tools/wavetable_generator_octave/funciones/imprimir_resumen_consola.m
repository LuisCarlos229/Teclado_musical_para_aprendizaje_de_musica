function imprimir_resumen_consola(nombres, stats_matrix)
    fprintf('\n===========================================================================================================================================\n');
    fprintf('                 RESUMEN ESTADÍSTICO DE SÍNTESIS BATCH (V4.1.0-alpha)                         \n');
    fprintf('===========================================================================================================================================\n');
    fprintf('%-12s %-11s %-11s %-9s %-8s %-9s %-9s %-11s %-9s %-11s %-9s %-8s\n', ...
        'Nota', 'F.Teorica', 'F.Real', 'Dif(Hz)', 'Dif(%)', 'MSE.G', 'SC.G', 'LSD.G(dB)', 'SC.B', 'LSD.B(dB)', 'Dif CFR', 'Dur(s)');
    fprintf('--------------------------------------------------------------------------------------------------------------------------------------------\n');
    % Fila de valores ideales
    fprintf('%-12s %-11s %-11s %-9s %-8s %-9s %-9s %-11s %-9s %-11s %-9s %-8s\n', ...
        '[Ideal]->', '-', '-', '0', '0', '0', '1', '0', '1', '0', '0', '-');
    fprintf('--------------------------------------------------------------------------------------------------------------------------------------------\n');

    for i = 1:length(nombres)
        fprintf('%-12s %-11.3f %-11.3f %-9.3f %-8.2f %-9.4f %-9.4f %-11.4f %-9.4f %-11.4f %-9.4f %-8.3f\n', ...
            nombres{i}, stats_matrix(i,1), stats_matrix(i,2), stats_matrix(i,3), stats_matrix(i,4), ...
            stats_matrix(i,5), stats_matrix(i,6), stats_matrix(i,7), stats_matrix(i,8), stats_matrix(i,9), stats_matrix(i,10), stats_matrix(i,11));
    end
    fprintf('===========================================================================================================================================\n');
end
